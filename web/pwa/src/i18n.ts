const DICTS: Record<string, Dict> = { en, cs, de, es, fr, ja, zh, uk, th };
export const UI_LANGS = Object.keys(DICTS);

/** Current UI language; follows the chosen transcript language. */
export const uiLang = signal<string>(baseLang(typeof navigator !== "undefined" ? navigator.language : "en"));

export function setUiLang(lang: string) {
  const b = baseLang(lang);
  uiLang.value = b;
  try {
    document.documentElement.lang = DICTS[b] ? b : "en";
  } catch {
    /* ssr */
  }
}

export function t(key: StrKey, vars?: Record<string, string | number>): string {
  const lang = uiLang.value;
  let s = DICTS[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** People can stay nameless until they ask or meet; show them as a localized "Guest". */
export function displayName(name?: string | null): string {
  return name?.trim() || t("guest");
}
